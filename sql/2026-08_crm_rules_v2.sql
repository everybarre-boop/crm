-- CRM 규칙 v2 — 2026-08-22 실제 발송에서 드러난 오분류 2건 + 새 규칙 1개
-- ----------------------------------------------------------------------------
-- 실행: npm run db:sql sql/2026-08_crm_rules_v2.sql
-- 되돌리기 어려운 SQL 은 아니지만(규칙 행만 건드린다), 습관대로:
--   npm run db:backup members  /  npm run db:backup sales
--
-- ⚠️ 이 파일은 idempotent 하다. 여러 번 돌려도 화면에서 손댄 값을 덮지 않는다
--    (`not ("파라미터" ? '키')` 조건 — 2026-08_crm.sql 의 seed 패턴과 같다).
--
-- 배경 — 왜 고치는가
--   ① 만료 임박이 1회권·체험권에 발동했다.
--      조건이 `잔여/전체 >= 0.3` 뿐이라, 전체=1·잔여=1 이면 비율이 **항상 1.0** 이라
--      무조건 통과한다. 그래서 체험권 회원에게
--        "아직 1회 남으셨어요. 추가 등록하시면 남은 횟수는 그대로 이월돼요!"
--      가 나갔다(2026-08-22 청담 이송은·김예지 — expiring 12건 중 2건).
--      1회권은 "다 쓰면 끝"이 정상이라 이월을 권할 대상이 아니다.
--      게다가 정렬순서상 만료임박(20)이 체험(40)을 이겨서 **올바른 체험 멘트까지 밀어냈다.**
--      → 파라미터 `최소전체횟수: 2` 신설. 코드는 추가로 체험권 자체도 제외한다.
--
--   ② 1회권을 반복 구매하는 드롭인 단골에게 아무 멘트도 안 나갔다.
--      'first-paid'(신규 등록 첫 수업)는 `최대누적: 3` 으로 막혀 있는데, 실측된
--      옥수 회원은 '체험 후 1회권' 등록건이 18개 · 누적 17회다. 신규가 아니라 단골이다.
--      → 새 규칙 'dropin-return'(1회권 재방문). 축하가 아니라 **정기권 제안**이 목적이다.
--
-- ⚠️ 코드(shared/crm-rules.mjs)의 DEFAULT_RULES 와 값을 맞춰 둘 것 — 둘 다 고친다.
--    코드는 DB 에 없는 규칙을 기본값으로 병합하므로(mergeRules) 이 SQL 을 안 돌려도
--    동작은 한다. 다만 관리자 화면에서 편집하려면 DB 행이 있어야 한다.
-- ============================================================================

-- ── ① 만료 임박: 최소전체횟수 하한 ──────────────────────────────────────────
-- 화면에서 이미 이 키를 손댔다면 건드리지 않는다.
update public.crm_rules
   set "파라미터" = "파라미터" || '{"최소전체횟수":2}'::jsonb,
       updated_at = now()
 where id = 'expiring'
   and not ("파라미터" ? '최소전체횟수');

-- ── ② 새 규칙: 1회권 재방문 ────────────────────────────────────────────────
-- 정렬순서 35 = 1인 1건 우선순위에서 신규(30)보다 뒤, 체험(40)보다 앞.
--   마일스톤(10) > 만료임박(20) > 신규(30) > **1회권 재방문(35)** > 체험(40)
-- 재발송억제일수 30 — 매주 오는 드롭인에게 같은 제안이 매번 나가면 안 된다.
-- 최소누적 4 = first-paid 의 최대누적(3) + 1 → 두 규칙이 겹치지 않는다.
insert into public.crm_rules
  (id, "라벨", "이모지", "슬랙발송", "정렬순서", "재발송억제일수", "파라미터", "템플릿", "예시멘트")
values
  ('dropin-return', '1회권 재방문', '🔁', true, 35, 30,
   '{"키워드":["1회권"],"최소누적":4}'::jsonb,
   '1회권으로 다시 방문 · {{수강권명}} (누적 {{누적횟수}}회)',
   '{{이름}}님, 또 오셨네요 반가워요! 정기 수강권으로 등록하시면 더 편하게 오실 수 있어요 😊')
on conflict (id) do nothing;

-- ── 점검 ───────────────────────────────────────────────────────────────────
select id,
       "라벨",
       "활성",
       "슬랙발송",
       "정렬순서"   as 우선순위,
       "재발송억제일수",
       "파라미터"
  from public.crm_rules
 order by "정렬순서";
