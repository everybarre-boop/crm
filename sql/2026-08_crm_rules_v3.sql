-- ============================================================================
-- CRM 규칙 v3 — 마일스톤 멘트가 "누적"을 1 높게 단언하던 것을 바로잡는다
-- ----------------------------------------------------------------------------
-- 먼저:  npm run db:backup crm_messages
-- 실행:  npm run db:sql sql/2026-08_crm_rules_v3.sql
--
-- 한 파일 = 한 트랜잭션. 재실행 안전(idempotent) — 이미 고쳐진 문구는 건드리지 않는다.
--
-- 🔥 배경 (2026-08-27 확인 · 전 지점 전 회차 재현)
--    슬랙에는  `*10회차!* (누적 10회)` 가 나가는데, 그 시점 members 의 누적은 **9** 였다.
--    강사가 스튜디오메이트 회원 페이지와 대조하면 **항상 정확히 1 이 부족**하다.
--    최근 2주 마일스톤 발송 21건 전부 `발송 회차 = 누적 + 1` (10·30·50·100 · 6개 지점).
--
--    원인은 두 겹이다.
--      ① 발송 시점 — 마일스톤은 내일 수업으로 N 회를 채우는 회원에게 **전날 밤** 나간다.
--         (`예정회차 = 누적 + 1` — shared/crm-rules.mjs). 이 시점 자체는 의도된 설계다.
--      ② 렌더 — 그런데 템플릿 변수 `누적횟수` 를 **예정회차로 덮어써서** 아직 오지 않은
--         수업까지 "누적"에 넣어 단언했다. 회차 안내는 사실 단언이라 이게 문제다.
--
--    이 파일이 고치는 건 ②(문구)다. ①(발송 시점)은 그대로 둔다 —
--    "이번 수업이 10번째" 는 강사가 수업에서 말할 때 사실이다.
--    누적 자체가 결석·횟수조정·만료소멸까지 세는 문제는 별개이고,
--    docs/NEXT-attendance-count.md 가 그 작업이다.
--
-- ⚠️ shared/crm-rules.mjs 의 DEFAULT_RULES · sql/2026-08_crm.sql 의 seed 도 같이 고쳐 뒀다.
--    ruleMap() 은 DB 행이 있으면 DB 를 우선하므로, **이 SQL 을 돌려야 실제 발송이 바뀐다.**
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1) 규칙 문구 교체
--    옛 문구와 정확히 일치할 때만 바꾼다 → 재실행 안전 + 관리자 화면에서 손댄 문구는 보존
-- ----------------------------------------------------------------------------
update public.crm_rules
   set "템플릿" = '*{{마일스톤}}회차!* (지금까지 {{누적횟수}}회 · 이번 수업이 {{마일스톤}}회차)'
 where id = 'milestone'
   and "템플릿" = '*{{마일스톤}}회차!* (누적 {{누적횟수}}회)';

update public.crm_rules
   set "예시멘트" = '{{이름}}님, 이번 수업이 {{마일스톤}}번째예요! 꾸준히 나오시는 게 정말 대단해요 👏'
 where id = 'milestone'
   and "예시멘트" = '{{이름}}님, 오늘로 {{마일스톤}}번째 수업이에요! 꾸준히 나오시는 게 정말 대단해요 👏';

-- ----------------------------------------------------------------------------
-- 2) 옛 문구로 나간 마일스톤 발송 이력 삭제
--
--    왜 지우나 — 마일스톤은 `재발송억제일수 = -1`(평생 1회)다. "(누적 10회)" 라는 틀린
--    수를 단언한 행이 억제 근거로 남아 있으면, 그 회원은 앞으로 **어떤 경로로도** 그 회차
--    축하를 다시 못 받는다.
--
--    ⚠️ 다만 발송 시점(①)은 그대로이므로, **이미 그 회차를 지나친 회원에게 이 삭제가
--       메시지를 다시 보내 주지는 않는다**(소급허용=false). 앞길을 막지 않을 뿐이다.
--       지난 마일스톤을 실제로 다시 보내려면 소급허용을 켜야 하는데, 그러면 "이번 수업이
--       N번째" 가 또 거짓말이 된다 — 그래서 켜지 않는다.
--
--    판정: 옛 템플릿으로 렌더된 행만 고른다(`(누적 N회)` 로 끝나는 멘트).
--    2026-08-27 실측 — 대상 21건, 그중 강사 피드백(실행여부/반응/메모)이 달린 행 0건.
--    피드백이 달린 행은 지우지 않는다(기록 보존).
-- ----------------------------------------------------------------------------
delete from public.crm_messages
 where rule_id = 'milestone'
   and "멘트" ~ '^\*[0-9]+회차!\* \(누적 [0-9]+회\)$'
   and "실행여부" is null
   and coalesce("반응", '') = ''
   and coalesce("메모", '') = '';

-- ----------------------------------------------------------------------------
-- 3) 점검
-- ----------------------------------------------------------------------------
select id, "템플릿", "예시멘트" from public.crm_rules where id = 'milestone';

select count(*) filter (where "멘트" ~ '^\*[0-9]+회차!\* \(누적 [0-9]+회\)$') as "남은_옛문구_발송분",
       count(*)                                                              as "마일스톤_발송분_전체"
from public.crm_messages where rule_id = 'milestone';
