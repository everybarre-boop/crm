-- ============================================================================
-- CRM 규칙 v4 — 만료 임박에서 "이미 재등록한 회원" 제외 (2026-09-09)
-- ----------------------------------------------------------------------------
-- 실행: npm run db:sql sql/2026-09_crm_rules_v4.sql
-- 규칙 행 하나의 파라미터만 건드린다(회원 데이터 불변). 습관대로 백업은 먼저:
--   npm run db:backup members
--
-- ⚠️ idempotent — 화면에서 이미 이 키를 손댔다면 덮지 않는다
--    (`not ("파라미터" ? '키')` — 2026-08_crm.sql 의 seed 패턴과 같다).
--
-- 배경 — 왜 고치는가
--   "{{이름}}님, … 추가 등록하시면 남은 횟수는 그대로 이월돼요!" 는 **다음 수강권을 이미
--   끊은 회원에게는 틀린 말**이다. 등록을 두 번 권하는 꼴이라 현장에서 신뢰를 깎는다.
--
-- 🔥 판정 기준 — "기존 종료일 이후에 시작한 수강권"이 아니다.
--   실측(2026-09-09 재업로드 후 · members 18,897행) 같은 사람의 연속한 등록건 9,995쌍:
--     · 이전 종료일 **이후** 시작        3,506쌍 (35%)
--     · 같은 날 시작                       131쌍 ( 1%)
--     · 이전 종료일보다 **먼저** 시작     6,358쌍 (63.6%)  ← 중앙값 −14일
--   결제한 날부터 새 수강권이 열리기 때문에, 재등록은 옛 권이 끝나기 전에 시작하는 게
--   오히려 정상이다. 그래서 "종료일 이후 시작"으로 걸면 그날의 만료임박 후보 31명 중
--   4명만 걸려 **실제 재등록자 6명 중 2명(33%)을 놓친다.**
--   ✅ 대신 **그 만료일 이후까지 유효한(= 더 늦게 끝나는) 다른 등록건**으로 판정한다(6명 전원).
--
-- 판정 구현은 shared/crm-rules.mjs 의 hasRenewalTicket 한 곳에만 있다(SQL 로 재구현 금지).
-- 이 SQL 은 그 조건을 켜는 파라미터를 DB 규칙 행에 심어 **관리자 화면에서 끌 수 있게** 할 뿐이다.
-- 코드는 DB 에 없는 키를 기본값으로 병합하므로(ruleMap) 이 파일을 안 돌려도 동작은 한다.
-- ============================================================================

update public.crm_rules
   set "파라미터" = "파라미터" || '{"재등록제외":true}'::jsonb,
       updated_at = now()
 where id = 'expiring'
   and not ("파라미터" ? '재등록제외');

-- ── 점검 ───────────────────────────────────────────────────────────────────
select id, "라벨", "활성", "슬랙발송", "정렬순서" as 우선순위, "재발송억제일수", "파라미터"::text as 파라미터
  from public.crm_rules
 where id = 'expiring';
