-- ============================================================================
-- CRM 규칙 v5 — 마일스톤 회차 개정 + 회차별 멘트 (2026-09-15)
-- ----------------------------------------------------------------------------
-- 실행: npm run db:sql sql/2026-09_crm_milestones_v5.sql
-- 규칙 행 하나의 파라미터만 건드린다(회원 데이터 불변). 습관대로 백업은 먼저:
--   npm run db:backup members
--
-- 무엇을 바꾸는가
--   ① 마일스톤 목록:  [10,30,50,100,150,200,300,500]
--                  → [22,50,100,150,200,250,300,350,400,450,500]
--      · 앞 단계(첫 수업 · 체험 후 등록 첫 수업)는 `trial` / `first-paid` 규칙이 이미
--        따로 맡는다. 마일스톤이 10·30 을 또 축하할 자리가 아니다.
--      · 50 회부터는 50 회 단위로 고르게 간다(250·350·400·450 이 새로 생겼다).
--   ② `마일스톤멘트` 키 추가 — **회차별 예시 멘트**를 담는 맵.
--      비어 있으면 지금처럼 공통 `예시멘트` 가 나간다(= 지금 당장은 문구가 안 바뀐다).
--      회차별로 다른 문장은 **관리자 화면 → CRM 성과 → 마일스톤 → 템플릿 편집**에서 넣는다.
--
-- ⚠️ ① 은 idempotent 가 아니라 **의도적 덮어쓰기**다 — 목록을 바꾸는 게 이 파일의 목적이라
--    화면에서 손댄 목록도 이 값으로 맞춘다. 두 번 돌려도 결과는 같다(값이 같으면 no-op).
--    반대로 ② 는 키가 없을 때만 넣는다 — 이미 써 둔 회차별 멘트를 지우면 안 된다.
--
-- ⚠️ 코드 기본값(shared/crm-rules.mjs 의 DEFAULT_RULES)과 짝이다. 둘 다 고칠 것.
--    코드는 DB 에 없는 키를 기본값으로 병합하므로(ruleMap) 이 파일을 안 돌려도 새 설치는
--    새 목록으로 동작한다. 이 SQL 은 **이미 옛 목록이 저장돼 있는 운영 DB** 를 위한 것이다.
--
-- 옛 회차 발송 이력은 지우지 않는다 — 10·30 회차를 이미 받은 회원은 그대로 두고,
-- 앞으로 22·50·100… 에서 다시 축하하면 된다(억제 키가 회차 숫자라 서로 간섭하지 않는다).
-- ============================================================================

update public.crm_rules
   set "파라미터" = "파라미터"
                 || jsonb_build_object('마일스톤',
                      '[22,50,100,150,200,250,300,350,400,450,500]'::jsonb),
       updated_at = now()
 where id = 'milestone'
   and "파라미터" -> '마일스톤'
       is distinct from '[22,50,100,150,200,250,300,350,400,450,500]'::jsonb;

update public.crm_rules
   set "파라미터" = "파라미터" || '{"마일스톤멘트":{}}'::jsonb,
       updated_at = now()
 where id = 'milestone'
   and not ("파라미터" ? '마일스톤멘트');

-- ── 점검 ───────────────────────────────────────────────────────────────────
select id,
       "라벨",
       "활성",
       "파라미터" -> '마일스톤'  as 회차목록,
       (select count(*) from jsonb_object_keys(
          coalesce("파라미터" -> '마일스톤멘트', '{}'::jsonb))) as 회차별멘트수,
       "예시멘트"                as 공통멘트
  from public.crm_rules
 where id = 'milestone';
